"""Loading the curated power data - every read of the curated tree.

Gold layout (the curated layer of the medallion tree raw -> fnd -> gold):
data/gold/<dataset>/<house>/<channel>.parquet with columns ts_us (int64,
UTC microseconds) and w (float64, active watts); episode thresholds in
data/gold/thresholds.json. Hand-curated data lives beside it in
data/gold_annot/ (layout + schema in data/gold_annot/README.md): device
profiles, the train/test split point, and cycle-mark CSVs. Pure reads
only - anything that processes these tables into an experiment view
(GT episodes, background floors, press lists) lives in the experiment
that consumes it.
"""

from __future__ import annotations

import json
import os

import pandas as pd

from wattwiser.paths import GOLD, ROOT

# Hand-curation store beside data/gold/ (layout + schema: data/gold_annot/README.md).
GOLD_ANNOT: str = os.path.join(ROOT, "data", "gold_annot")

GT_CYCLE_COLS: list[str] = ["device", "t_on_us", "t_off_us", "source", "provenance"]


def gold_parquet_path(dataset: str, house: str, channel: str) -> str:
    """Path of one gold-layer parquet (channel = meter or computed table)."""
    return os.path.join(GOLD, dataset, house, f"{channel}.parquet")


def annot_csv_path(dataset: str, house: str, name: str) -> str:
    """Path of one gold_annot csv (layout + schema: data/gold_annot/README.md)."""
    return os.path.join(GOLD_ANNOT, dataset, house, f"{name}.csv")


def load_power_series(path: str) -> pd.DataFrame:
    """Load one gold parquet as a timestamp-sorted [ts_us, w] frame."""
    return pd.read_parquet(path)[["ts_us", "w"]].sort_values("ts_us").reset_index(drop=True)


def load_thresholds() -> dict:
    """Episode thresholds for every dataset (data/gold/thresholds.json),
    keyed dataset -> house -> channel (adopted as-is from the quarantined
    client reference; the labeling convention, not measured truth)."""
    with open(os.path.join(GOLD, "thresholds.json")) as fh:
        return json.load(fh)


def load_device_profiles(dataset: str, house: str) -> pd.DataFrame:
    """Device profile rules from gold_annot (device_profile.csv)."""
    return pd.read_csv(annot_csv_path(dataset, house, "device_profile"))


def load_split_us(dataset: str, house: str) -> int:
    """The train/test split point of one house's recording (splits.csv,
    one row): hand marks, profiles, and simulation all live before it;
    the span after is held out for evaluation."""
    return int(pd.read_csv(annot_csv_path(dataset, house, "splits"))["split_us"].iloc[0])


def load_gt_cycles(dataset: str, house: str) -> pd.DataFrame:
    """Every ground-truth cycle for one house: one row = one device run in
    the recording, from switch-on (t_on_us) to switch-off (t_off_us).
    Marks come from two files with different owners: made by hand
    (manual_cycles.csv) or generated by a rule (rule_cycles.csv); the
    'provenance' column says which. Missing or empty files are skipped."""
    frames: list[pd.DataFrame] = []
    for name, provenance in (("manual_cycles", "manual"), ("rule_cycles", "rule")):
        try:
            marks = pd.read_csv(annot_csv_path(dataset, house, name))
        except (FileNotFoundError, pd.errors.EmptyDataError):
            continue
        marks["provenance"] = provenance
        frames.append(marks)
    if not frames:
        return pd.DataFrame(columns=GT_CYCLE_COLS)
    return pd.concat(frames, ignore_index=True)
